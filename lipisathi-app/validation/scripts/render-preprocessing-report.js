#!/usr/bin/env node
/**
 * M8 Phase 4 - render the markdown report from M8-phase4-preprocessing-results.json.
 * Pure formatting; deterministic; computes no new metrics except simple ratios of existing counts.
 * Run after calculate-preprocessing-cer-wer.js.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const rdir = path.resolve(here, '../results');
const R = JSON.parse(fs.readFileSync(path.join(rdir, 'M8-phase4-preprocessing-results.json'), 'utf8'));

const f = (x, d = 3) => (x === null || x === undefined ? 'n/a' : Number(x).toFixed(d));
const V = R.variants;
const control = V.find((v) => v.id === 'full__original');
const base = R.m7_stored_baseline_corpus;
const ids = [...new Set(R.per_run.map((r) => r.image_id))];
const L = [];

L.push('# M8 Phase 4 - Preprocessing Results (CER/WER)');
L.push('');
L.push('> Generated by `validation/scripts/render-preprocessing-report.js` from `M8-phase4-preprocessing-results.json`. Do not edit by hand.');
L.push('');
L.push('## Scope and caveats');
L.push('');
L.push('- **Dataset:** 12 images (8 Hindi, 4 Telugu). This is an exploratory set, **not a representative benchmark**. Differences between variants are descriptive and were not statistically tested.');
L.push('- **Reference:** `verified_text` from `ground-truth.json`. Human verification was *attested by the project owner*; reviewer name, language fluency and per-record notes were not recorded.');
L.push('- **Metrics:** CER/WER = edit distance / reference length, aggregated at corpus level (sum of edits / sum of reference units). Lower is better. These are error rates, not accuracy. Values above 1.0 are valid when OCR output contains many insertions.');
L.push(`- **Reference size:** ${control.overall.total_reference_characters} characters and ${control.overall.total_reference_words} words in total (small).`);
L.push('- **Whole image** = the full photo. **Sign crop** = a hand-defined box per image (`sign-crop-regions.json`, fixed before any OCR ran). The crop removes scene clutter only. **English text on the sign is still inside the crop** and counts as insertions.');
L.push('- Preprocessing ran in the browser canvas and the result was uploaded through the existing UI. OCR engine, models, and app code are unchanged. Each cell is a single run.');
L.push('- OCR ran in system Google Chrome through Playwright, because the bundled Chromium could not be downloaded in this environment (TLS certificate error). The control below shows the baseline output was unaffected.');
L.push('');
L.push('## Control: re-run vs stored M7 baseline');
L.push('');
L.push(`The untouched \`full__original\` re-run produced OCR text identical to the stored M7 output for **${R.m7_rerun_consistency.images_identical_to_M7_text}/12** images. Corpus CER ${f(control.overall.corpus_CER)} / WER ${f(control.overall.corpus_WER)} versus the stored M7 baseline ${f(base.corpus_CER)} / ${f(base.corpus_WER)}. OCR output looks deterministic here, so differences between variants come from the preprocessing.`);
L.push('');
L.push('## Corpus results by variant');
L.push('');
L.push('| Variant | Corpus CER | Corpus WER | Hindi CER | Telugu CER | Char ins / del / sub | OCR chars emitted | Mean conf | Mean time (s) | Images with lower CER than full__original |');
L.push('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
for (const v of V) {
  const o = v.overall;
  L.push(`| ${v.id} | ${f(o.corpus_CER)} | ${f(o.corpus_WER)} | ${f(v.Hindi.corpus_CER)} | ${f(v.Telugu.corpus_CER)} | ${o.character_insertions} / ${o.character_deletions} / ${o.character_substitutions} | ${o.total_OCR_characters} | ${f(o.mean_tesseract_confidence, 1)} | ${f(o.mean_processing_time_seconds, 2)} | ${v.vs_full_original_rerun.images_lower_CER}/12 |`);
}
L.push('');
L.push('## Per-image CER');
L.push('');
L.push('| Image | ' + V.map((v) => v.id).join(' | ') + ' |');
L.push('|---|' + V.map(() => '---:').join('|') + '|');
for (const id of ids) {
  L.push(`| ${id} | ` + V.map((v) => f(R.per_run.find((r) => r.variant_id === v.id && r.image_id === id)?.CER, 2)).join(' | ') + ' |');
}
L.push('');
L.push('## Interpretation (descriptive only)');
L.push('');
const ranked = [...V].sort((a, b) => a.overall.corpus_CER - b.overall.corpus_CER);
const share = V.map((v) => v.overall.character_insertions / v.overall.total_character_edit_distance);
L.push(`- Lowest corpus CER in this run: **${ranked[0].id}** (${f(ranked[0].overall.corpus_CER)}). Highest: **${ranked.at(-1).id}** (${f(ranked.at(-1).overall.corpus_CER)}).`);
L.push(`- Insertions make up ${f(Math.min(...share) * 100, 0)}-${f(Math.max(...share) * 100, 0)}% of character edits across variants. CER/WER here mostly track *how much extra text OCR emits*, not how well the sign text is recognised. A variant can score a lower CER just by emitting less text.`);
L.push('- Cropping to the sign has by far the largest effect. It is a clutter-removal effect, not a recognition improvement, and it depends on a manually chosen region that a real app would not have without a text-region detection step.');
L.push('- Grayscale and contrast stretch lowered corpus CER in the whole-image condition (mainly through less emitted text). The effect is smaller than the crop effect, mixed across images (7 of 12 improved, 5 of 12 got worse, see the per-image table), and differs between Hindi and Telugu. In the crop condition grayscale lowered corpus CER, and contrast stretch did not beat grayscale.');
L.push('- 2x upscaling increased the amount of emitted text and raised CER in this run, in both conditions.');
L.push('- Tesseract confidence differences between variants are small and do not track CER closely.');
L.push('- With 12 images and one run per cell, **no variant can be called a reliable improvement**. A cleaner test would need sign-only ground truth and automatic text-region detection.');
L.push('');
L.push('## Files');
L.push('');
L.push('- Raw OCR text per run: `validation/results/M8-phase4-ocr-runs.json`');
L.push('- Machine-readable scores: `validation/results/M8-phase4-preprocessing-results.json`');
L.push('- Crop boxes: `validation/metadata/sign-crop-regions.json`');
L.push('');
const out = path.join(rdir, 'M8-phase4-preprocessing-results.md');
fs.writeFileSync(out, L.join('\n'));
console.log('Wrote ' + path.relative(process.cwd(), out));
